package tpkt

import "testing"

func FuzzDecode(f *testing.F) {
	// Seed with a variety of structurally interesting packets.
	seeds := [][]byte{
		// Minimum valid frame.
		{0x03, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03},
		// Invalid version.
		{0x02, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03},
		// Invalid reserved byte.
		{0x03, 0x01, 0x00, 0x07, 0x01, 0x02, 0x03},
		// Declared length smaller than actual.
		{0x03, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03, 0x00},
		// Declared length larger than actual.
		{0x03, 0x00, 0x00, 0x08, 0x01, 0x02, 0x03},
		// Truncated header.
		{0x03, 0x00, 0x00},
		// Truncated payload.
		{0x03, 0x00, 0x00, 0x07, 0x01},
	}
	for _, s := range seeds {
		f.Add(append([]byte(nil), s...))
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		// Decode must never panic.
		_, _ = Decode(data)
	})
}

func FuzzParse(f *testing.F) {
	// Seed with the same structural variants used for FuzzDecode.
	seeds := [][]byte{
		{0x03, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03},
		{0x02, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03},
		{0x03, 0x01, 0x00, 0x07, 0x01, 0x02, 0x03},
		{0x03, 0x00, 0x00, 0x07, 0x01, 0x02, 0x03, 0x00},
		{0x03, 0x00, 0x00, 0x08, 0x01, 0x02, 0x03},
		{0x03, 0x00, 0x00},
		{0x03, 0x00, 0x00, 0x07, 0x01},
	}
	for _, s := range seeds {
		f.Add(append([]byte(nil), s...))
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		// Parse must never panic.
		_, _ = Parse(data)
	})
}
